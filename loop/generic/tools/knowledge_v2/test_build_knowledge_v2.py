def sha_tree(d):
    fs = sorted(glob.glob(os.path.join(d, "*.tsv"))) + [os.path.join(d, "KNOWLEDGE_BRIEF.md")]
    def h(f):
        with open(f, "rb") as fh: return hashlib.sha256(fh.read()).hexdigest()
    return {os.path.basename(f): h(f) for f in fs if os.path.exists(f)}

def csv_rows(path):
    import csv
    with open(path, encoding="utf-8", newline="") as fh: return list(csv.DictReader(fh, delimiter="\t"))

def run(args, cwd):
    return subprocess.run([sys.executable, "-B"] + args, cwd=cwd, capture_output=True, text=True)

def write_pack(pk):
    d = mkd(); path = os.path.join(d, "pack.json")
    with open(path, "w", encoding="utf-8") as fh: json.dump(pk, fh)
    return path

def strat_copy(extra_mechs=(), bars=None):
    """a temp copy of packs/strategy_v0.json; its mechanisms_file -> a temp copy of PACK_V1/MECHANISMS.txt plus extra lines"""
    pk = jload(STRAT); d = mkd()
    with open(os.path.join(os.path.dirname(STRAT), pk["mechanisms_file"]), encoding="utf-8") as fh: src = fh.read().rstrip("\n") + "\n"
    with open(os.path.join(d, "MECHANISMS.txt"), "w", encoding="utf-8") as fh: fh.write(src + "".join(m + "\n" for m in extra_mechs))
    pk["mechanisms_file"] = "MECHANISMS.txt"
    if bars: pk["status_bars"] = dict(bars)
    path = os.path.join(d, "pack.json")
    with open(path, "w", encoding="utf-8") as fh: json.dump(pk, fh)
    return path

